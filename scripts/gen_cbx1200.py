def run(cmd: list[str], cwd: Path | None = None) -> str:
    p = subprocess.run(cmd, cwd=str(cwd) if cwd else None, capture_output=True, text=True)
    if p.returncode != 0:
        raise RuntimeError(
            f"Command failed: {' '.join(cmd)}\nSTDOUT:\n{p.stdout}\nSTDERR:\n{p.stderr}"
        )
    return p.stdout.strip()


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def git_clone_or_update(repo_url: str, dest: Path, pin: str | None = None) -> None:
    """Materialize ``dest`` at exactly ``pin``, fetching that commit directly.

    The previous version cloned the default branch at depth 1 and then let the
    caller assert HEAD equalled the pin. It never fetched or checked the pin
    out, so the assertion failed the moment upstream moved, which it has: both
    generators aborted from a clean checkout with
    ``HEAD=<today's tip> expected=<pinned sha>``. The pinned datasets could not
    be regenerated by the scripts that claim to produce them.

    Fetching the commit by sha rather than cloning a branch and hoping is also
    cheaper and exact: one commit, no history, and no dependence on where the
    default branch happens to point. GitHub serves a sha to ``git fetch``,
    which is what makes this work without a full clone.
    """
    if not (dest / ".git").exists():
        dest.mkdir(parents=True, exist_ok=True)
        run(["git", "init", "--quiet", str(dest)])
        run(["git", "remote", "add", "origin", repo_url], cwd=dest)
    if pin:
        run(["git", "fetch", "--quiet", "--depth", "1", "origin", pin], cwd=dest)
        run(["git", "checkout", "--quiet", "--force", pin], cwd=dest)
    else:
        # No pin recorded for this repo: take the default branch, and say so by
        # leaving the caller's HEAD check to pass trivially.
        run(["git", "fetch", "--quiet", "--depth", "1", "origin", "HEAD"], cwd=dest)
        run(["git", "checkout", "--quiet", "--force", "FETCH_HEAD"], cwd=dest)


def git_head_commit(dest: Path) -> str:
    return run(["git", "rev-parse", "HEAD"], cwd=dest)


def read_jsonl_texts(path: Path, text_fields: list[str]) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    with path.open("r", encoding="utf-8") as f:
        for i, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                continue
            for tf in text_fields:
                v = obj.get(tf)
                if isinstance(v, str) and v.strip():
                    out.append((f"line:{i}:{tf}", v.strip()))
    return out


def read_csv_column(path: Path, colname: str) -> list[tuple[str, str]]:
    import csv

    out: list[tuple[str, str]] = []
    with path.open("r", encoding="utf-8", newline="") as f:
        r = csv.DictReader(f)
        for i, row in enumerate(r, start=2):
            v = row.get(colname, "")
            if isinstance(v, str) and v.strip():
                out.append((f"line:{i}:{colname}", v.strip()))
    return out


def is_explicit(text: str) -> bool:
    t = text.lower()
    return any(re.search(pat, t) for pat in EXPLICIT_MARKERS)


def pick_weighted(rng: random.Random, items: list[tuple[str, float]]) -> str:
    total = sum(w for _, w in items)
    x = rng.random() * total
    acc = 0.0
    for v, w in items:
        acc += w
        if x <= acc:
            return v
    return items[-1][0]


