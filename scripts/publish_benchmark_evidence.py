"""Extract the published surface-control evidence from the tracked comparison.

The public pages quote surface-control numbers. Until now those numbers pointed
at `benchmarks/runs/`, which is not committed, so a reader could not fetch
anything that produced them. This writes a small extract next to the pages that
cite it, carrying the rows actually rendered plus the provenance needed to
re-run them.

Only extracts are published. The raw runs are 130MB and nobody audits them.

    python scripts/publish_benchmark_evidence.py           # write
    python scripts/publish_benchmark_evidence.py --check   # verify, exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "benchmarks" / "results" / "comparison.json"
PUBLISHED = ROOT / "benchmarks" / "published"
SURFACE_JSON = PUBLISHED / "surface_controls.json"
SURFACE_MD = PUBLISHED / "surface_controls.md"

# Rendered on the public pages, in the order they appear.
PUBLISHED_STRATEGIES = (
    "guardllm_surface",
    "strict_schema_stack",
    "casbin_rbac",
    "surface_stack",
    "policy_opa",
    "schema_jsonschema",
    "redis_rate_limit",
    "no_defense_surface",
)


def outputs() -> set[Path]:
    """Every file this generator writes."""
    return {SURFACE_JSON.resolve(), SURFACE_MD.resolve()}


def build() -> dict:
    source = json.loads(SOURCE.read_text())
    surface = source["surface_only"]
    strategies = surface["strategies"]
    missing = [name for name in PUBLISHED_STRATEGIES if name not in strategies]
    if missing:
        raise SystemExit(f"comparison.json is missing published strategies: {missing}")
    return {
        "_comment": (
            "Extract of the surface-control results published on the homepage and "
            "the canonical results page. Generated by "
            "scripts/publish_benchmark_evidence.py from benchmarks/results/comparison.json. "
            "Do not edit by hand."
        ),
        "provenance": {
            "source_artifact": "benchmarks/results/comparison.json",
            "generated_at": source["generated_at"],
            "run_id": source["run_id"],
            "git_sha_short": source["git_sha_short"],
            "dataset_hash": source["dataset_hash"],
            "suite_filter": source["suite_filter"],
            # comparison.json is produced by compare_mitigations.py, which
            # defaults to --dataset-id canonical-v1 and so needs the dataset
            # built first; the bare command failed on a clean clone because
            # benchmarks/datasets/ is gitignored. The build step is part of the
            # reproduce path. (Regenerating today yields the current corpus,
            # not this frozen snapshot; see the note in REPRODUCE.md.)
            "reproduce": (
                "python benchmarks/build_dataset.py --dataset-id canonical-v1 "
                "&& python benchmarks/compare_mitigations.py"
            ),
        },
        "surface_controls": {
            "case_count": surface["count"],
            "strategies": {
                name: {
                    "passed": strategies[name]["passed"],
                    "total": strategies[name]["total"],
                    "pass_rate": strategies[name]["pass_rate"],
                }
                for name in PUBLISHED_STRATEGIES
            },
        },
    }


def render(bundle: dict) -> str:
    prov = bundle["provenance"]
    surface = bundle["surface_controls"]
    rows = "\n".join(
        f"| `{name}` | {v['passed']} | {v['total']} | {v['pass_rate']}% |"
        for name, v in surface["strategies"].items()
    )
    return f"""<!-- Generated by scripts/publish_benchmark_evidence.py. Do not edit by hand. -->
# Surface controls: published evidence

Every surface-control figure quoted on the homepage and the canonical results
page comes from this extract, which is generated from the tracked
[`comparison.json`](../results/comparison.json).

## Provenance

| field | value |
|---|---|
| source artifact | `{prov["source_artifact"]}` |
| run id | `{prov["run_id"]}` |
| commit | `{prov["git_sha_short"]}` |
| dataset hash | `{prov["dataset_hash"]}` |
| suite filter | `{prov["suite_filter"]}` |
| generated at | `{prov["generated_at"]}` |
| reproduce | `{prov["reproduce"]}` |

## Results

{surface["case_count"]} surface cases.

| Strategy | Passed | Total | Pass rate |
|---|---:|---:|---:|
{rows}

## Scope

This bundle covers surface controls only. The prompt-injection vendor
comparison is not published here: the `injection_only` section of the source
artifact holds zero records, so those figures cannot be traced to a committed
artifact and remain labelled as reported rather than verifiable.
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    bundle = build()
    payload = json.dumps(bundle, indent=2, sort_keys=True) + "\n"
    markdown = render(bundle)

    if args.check:
        for path, expected in ((SURFACE_JSON, payload), (SURFACE_MD, markdown)):
            if not path.exists():
                print(f"missing published evidence: {path.relative_to(ROOT)}")
                return 1
            if path.read_text() != expected:
                print(f"published evidence is stale: {path.relative_to(ROOT)}")
                return 1
        print("published benchmark evidence is current")
        return 0

    PUBLISHED.mkdir(parents=True, exist_ok=True)
    SURFACE_JSON.write_text(payload)
    SURFACE_MD.write_text(markdown)
    print(f"wrote {SURFACE_JSON.relative_to(ROOT)} and {SURFACE_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
