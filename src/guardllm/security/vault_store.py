# Encrypted local file
# ---------------------------------------------------------------------------

#: Header, and the AEAD's associated data. Binding the format version into the
#: authenticated data is what stops a future format being replayed as this one.
_MAGIC = b"GLVAULT1"
_NONCE_BYTES = 12


def _aesgcm():
    """AES-GCM from ``cryptography``, imported lazily.

    Optional for the same reason wasmtime is: the library's controls all work
    without it, and a core install should not carry a dependency it never
    calls. Not optional in the sense that a plaintext fallback exists, because
    there is no plaintext fallback: without this the store refuses to write.

    The stdlib has no AEAD, and the alternative to a well-reviewed dependency
    here is a hand-rolled construction in a security product, which is worse
    than the dependency by a wide margin.
    """
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    except ImportError as exc:  # pragma: no cover - exercised by the extras test
        raise VaultStoreError(
            "an encrypted vault file needs the 'cryptography' package, which is not "
            "part of the core install. Install guardllm[vault]."
        ) from exc
    return AESGCM


def generate_key() -> str:
    """A fresh 256-bit key, base64, for an operator to store in a secret manager.

    Returned as text and never written anywhere by this library. Losing it
    means losing every token in the file, which is the intended property: a
    key recoverable from the deployment that holds the ciphertext is not
    protecting anything.
    """
    return base64.b64encode(secrets.token_bytes(KEY_BYTES)).decode("ascii")


def _coerce_key(key: bytes | str) -> bytes:
    if isinstance(key, str):
        try:
            key = base64.b64decode(key, validate=True)
        except ValueError as exc:
            raise VaultStoreError("vault key: not valid base64") from exc
    if len(key) != KEY_BYTES:
        raise VaultStoreError(
            f"vault key: must be {KEY_BYTES} bytes ({KEY_BYTES * 8} bits), got {len(key)}"
        )
    # An all-zero key is what an uninitialized buffer or an unset environment
    # variable decoded from a placeholder looks like. It is a valid AES key,
    # which is exactly the problem: the file would be encrypted under a
    # constant and would read back cleanly in the deployment that wrote it.
    if not any(key):
        raise VaultStoreError("vault key: refusing an all-zero key")
    return key


class EncryptedFileVaultStore:
    """One local file, AES-256-GCM, key supplied by the caller.

    The reference implementation of ``VaultStore``: enough for a single gateway
    that needs identity to survive a restart, and deliberately not more. It has
    no rotation, no escrow, no replication, and no access control beyond the
    file mode, all of which belong to key management rather than to the seam.

    What it does hold:

    - **Authenticated.** The header is associated data, so a truncated or
      edited file fails to open rather than opening short. Silent truncation
      would drop entries, and a dropped entry is a live token that stops
      resolving.
    - **Atomic.** Written to a temporary file in the same directory and moved
      into place, so a crash mid-write leaves the previous snapshot rather than
      half of the new one.
    - **0600.** Created through ``mkstemp``, which never has a readable moment.

    What it does not hold, said plainly: the *absence* of the file is not
    authenticated. Deleting it is indistinguishable from a first run, and the
    vault comes up empty. That is a denial of continuity, not a disclosure, and
    the remedy is filesystem permissions rather than cryptography.
    """

    def __init__(self, path: str | Path, *, key: bytes | str) -> None:
        self._path = Path(path)
        self._key = _coerce_key(key)

    @classmethod
    def from_env(
        cls, path: str | Path, *, var: str = "GUARDLLM_VAULT_KEY"
    ) -> EncryptedFileVaultStore:
        """Take the key from an environment variable holding base64.

        Refuses when the variable is unset rather than falling back to a
        generated key, because a generated key means the previous file is
        unreadable and the deployment would come up looking healthy and empty.
        """
        raw = os.environ.get(var)
        if not raw:
            raise VaultStoreError(
                f"vault key: {var} is not set. Generate one with "
                "guardllm.security.vault_store.generate_key() and store it in a secret manager."
            )
        return cls(path, key=raw)

    @property
    def path(self) -> Path:
        return self._path

    def load(self) -> VaultSnapshot | None:
        if not self._path.exists():
            return None
        blob = self._path.read_bytes()
        if len(blob) < len(_MAGIC) + _NONCE_BYTES:
            raise VaultStoreError(f"vault snapshot: {self._path} is too short to be a vault file")
        header, nonce, ciphertext = (
            blob[: len(_MAGIC)],
            blob[len(_MAGIC) : len(_MAGIC) + _NONCE_BYTES],
            blob[len(_MAGIC) + _NONCE_BYTES :],
        )
        if header != _MAGIC:
            raise VaultStoreError(f"vault snapshot: {self._path} is not a GuardLLM vault file")
        AESGCM = _aesgcm()
        try:
            plaintext = AESGCM(self._key).decrypt(nonce, ciphertext, header)
        except Exception as exc:
            # Deliberately one message for a wrong key and for a tampered file.
            # Distinguishing them tells an attacker which of the two they have.
            raise VaultStoreError(
                f"vault snapshot: {self._path} did not authenticate. The key is wrong "
                "or the file was modified; it is not being read as an empty vault."
            ) from exc
        return _from_json(plaintext)

    def save(self, snapshot: VaultSnapshot) -> None:
        AESGCM = _aesgcm()
        # A fresh random 96-bit nonce per write. Safe well past any realistic
        # number of writes under one key; rotation, which would raise that
        # ceiling further, is key management and sits above this class.
        nonce = secrets.token_bytes(_NONCE_BYTES)
        ciphertext = AESGCM(self._key).encrypt(nonce, _to_json(snapshot), _MAGIC)
        blob = _MAGIC + nonce + ciphertext

        parent = self._path.parent
        parent.mkdir(parents=True, exist_ok=True)
        # Same directory, so the replace below is a rename within one
        # filesystem and therefore atomic. mkstemp gives 0600 from creation.
        fd, tmp = tempfile.mkstemp(dir=str(parent), prefix=".vault-", suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(blob)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp, self._path)
        except BaseException:
            # A leftover temp file holds ciphertext under the live key. Not a
            # disclosure, but it is an unreferenced copy of the vault.
            try:
                os.unlink(tmp)
            except OSError:  # pragma: no cover - the replace already consumed it
                pass
            raise

    def purge(self) -> None:
        try:
            self._path.unlink()
        except FileNotFoundError:
            pass
