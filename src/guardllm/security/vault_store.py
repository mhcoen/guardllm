# Serialization
# ---------------------------------------------------------------------------


def _to_json(snapshot: VaultSnapshot) -> bytes:
    document = {
        "version": snapshot.version,
        "source_key": base64.b64encode(snapshot.source_key).decode("ascii"),
        # Class by name, matching what render_token puts in the token itself.
        # The enum's value is the wire form elsewhere; using one form in both
        # places is how a rename would go unnoticed in exactly one of them.
        "entries": [
            {"class": e.pii_class.name, "value": e.value, "body": e.body} for e in snapshot.entries
        ],
        "sources": [list(s) for s in snapshot.sources],
        "seeded": [[value, cls.name] for value, cls in snapshot.seeded],
    }
    return json.dumps(document, separators=(",", ":")).encode("utf-8")


def _check_version(version: object) -> None:
    if isinstance(version, bool) or not isinstance(version, int):
        raise VaultStoreError(
            f"vault snapshot: version must be an integer, got {type(version).__name__}"
        )
    if version in SUPPORTED_VAULT_SNAPSHOT_VERSIONS:
        return
    if version > VAULT_SNAPSHOT_VERSION:
        raise VaultStoreError(
            f"vault snapshot: version {version} is newer than this build understands "
            f"(supports {sorted(SUPPORTED_VAULT_SNAPSHOT_VERSIONS)}). Upgrade guardllm "
            "rather than deleting the file: the entries it holds are live tokens."
        )
    raise VaultStoreError(
        f"vault snapshot: version {version} is no longer supported "
        f"(supports {sorted(SUPPORTED_VAULT_SNAPSHOT_VERSIONS)})."
    )


def _from_json(raw: bytes) -> VaultSnapshot:
    try:
        document = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise VaultStoreError(f"vault snapshot: not readable as JSON ({exc})") from exc
    if not isinstance(document, dict):
        raise VaultStoreError("vault snapshot: expected a JSON object")
    _check_version(document.get("version"))

    def _class(name: object, where: str) -> PIIClass:
        # An unknown class is refused rather than dropped. Dropping it would
        # discard live entries and leave the tokens for them in the host's
        # transcript resolving to nothing.
        try:
            return PIIClass[str(name)]
        except KeyError as exc:
            raise VaultStoreError(f"vault snapshot: unknown PII class {name!r} in {where}") from exc

    try:
        entries = tuple(
            VaultEntry(pii_class=_class(e["class"], "entries"), value=e["value"], body=e["body"])
            for e in document.get("entries", ())
        )
        sources = tuple((str(s[0]), str(s[1]), str(s[2])) for s in document.get("sources", ()))
        seeded = tuple((str(v), _class(c, "seeded")) for v, c in document.get("seeded", ()))
        source_key = base64.b64decode(document.get("source_key", ""), validate=True)
    except (KeyError, TypeError, IndexError, ValueError) as exc:
        raise VaultStoreError(f"vault snapshot: malformed document ({exc})") from exc

    return VaultSnapshot(
        entries=entries,
        sources=sources,
        source_key=source_key,
        seeded=seeded,
        version=int(document["version"]) if "version" in document else VAULT_SNAPSHOT_VERSION,
    )


