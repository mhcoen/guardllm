"""Persisting the privacy vault, so an identity survives a restart.

The vault in ``privacy_vault`` is session state by construction: five in-memory
structures and a per-session key, dropped by ``clear`` and gone with the
process. That is the right default and this module does not change it. What it
adds is a seam for the deployment that needs the opposite, and one
implementation of that seam.

**A persisted vault is a different security object from an in-memory one.**
In memory it is an optimization: the plaintext it holds was already in the
caller's request. On disk it is a re-identification database, a single file
that maps every token a provider has seen back to the person behind it, and it
outlives the request, the process, and usually the incident. So this module
encrypts from its first commit rather than deferring it. A plaintext local
store would have been a smaller change and would have made the class docstring
in ``privacy_vault`` false in public.

**The caller supplies the key, and nothing here will invent one.** A key
generated by the library and written beside the ciphertext is not encryption at
rest; it is an obfuscated file plus a claim. ``generate_key`` exists to make a
key an operator can put in a secret manager, and there is no code path that
persists one. That is also why key *management* is a separate piece of work:
rotation, escrow, and a KMS-backed key all sit on top of this interface without
changing it.

**Continuity is what persistence buys, not protection.** Nothing crosses to the
provider that would not have crossed before: personal data is withheld either
way, and an unresolvable token still fails the call rather than resolving to
the wrong person. What a restart loses without a store is co-reference, so the
same person is issued a second token and a transcript from before the restart
stops resolving at all. That is an operational property, which is why the
ephemeral vault remains honest for deployments that do not need it.
"""

from __future__ import annotations

import base64
import json
import os
import secrets
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Protocol, runtime_checkable

from guardllm.security.types import PIIClass

__all__ = [
    "VAULT_SNAPSHOT_VERSION",
    "SUPPORTED_VAULT_SNAPSHOT_VERSIONS",
    "EncryptedFileVaultStore",
    "MemoryVaultStore",
    "VaultEntry",
    "VaultSnapshot",
    "VaultStore",
    "VaultStoreError",
    "generate_key",
]


#: The version of the persisted snapshot format.
#:
#: A third long-lived interface, for the same reason as the policy file and the
#: Rego input document: a customer-hosted deployment writes this file with one
#: release and reads it with another, and a vault file that cannot be read is a
#: population of live tokens that stop resolving. Within a version, fields may
#: be ADDED and a reader that does not know them ignores them. No field is
#: removed, renamed, or given a new meaning. Anything else increments this.
VAULT_SNAPSHOT_VERSION = 1

#: Every version this build can read. An unrecognized one is refused rather
#: than guessed at, and newer is distinguished from retired because the
#: remedies are opposite.
SUPPORTED_VAULT_SNAPSHOT_VERSIONS = frozenset({1})

#: 256-bit keys only. Accepting a short key would let a deployment configure
#: itself down to a strength nobody chose, and there is no reason to offer the
#: choice: the operator generates the key with ``generate_key``.
KEY_BYTES = 32


class VaultStoreError(RuntimeError):
    """A snapshot could not be read or written.

    Always raised, never swallowed into an empty vault. Starting empty after a
    failed read looks like a fresh session and is not one: every token already
    in the host's transcript silently stops resolving, and the same people are
    re-tokenized under new identifiers.
    """


@dataclass(frozen=True)
class VaultEntry:
    """One issued token: the value, its class, and the codeword body.

    ``body`` rather than the rendered token, because everything else the vault
    indexes is derived from the body and storing the derived forms too would
    let a file disagree with itself.

    ``value`` is real plaintext and is excluded from ``repr`` for the reason
    the vault excludes it everywhere else: one traced or logged snapshot
    aggregates every identifier a session saw.
    """

    pii_class: PIIClass
    value: str = field(repr=False)
    body: str


@dataclass(frozen=True)
class VaultSnapshot:
    """Everything a vault needs to resume issuing and resolving.

    Deliberately not everything the vault holds. The payload index, the issued
    body set, and the trigram index are all functions of ``entries``, so they
    are rebuilt on load rather than stored: a stored index can be inconsistent
    with the entries it indexes, and the failure that causes is a token that
    resolves to the wrong person.

    ``source_key`` is here because it is not derivable. Past the source-handle
    cache cap the vault derives handles by HMAC under it, so a restart with a
    fresh key would re-label sources the model had already been shown.
    """

    entries: tuple[VaultEntry, ...] = ()
    #: (source_type, source_id, handle)
    sources: tuple[tuple[str, str, str], ...] = ()
    #: The per-session HMAC key for derived source handles.
    source_key: bytes = field(default=b"", repr=False)
    #: (normalized value, class) declared by the host, not detected.
    seeded: tuple[tuple[str, PIIClass], ...] = field(default=(), repr=False)
    version: int = VAULT_SNAPSHOT_VERSION

    def __repr__(self) -> str:
        return (
            f"VaultSnapshot(version={self.version}, entries={len(self.entries)}, "
            f"sources={len(self.sources)}, seeded={len(self.seeded)})"
        )


@runtime_checkable
class VaultStore(Protocol):
    """Where a snapshot goes between processes.

    Three methods, because a fourth would have to be a partial write and there
    is no correct partial write of this object: an entry list missing its
    source key resolves tokens while re-labelling sources.

    An implementation is free to be a database, a KMS-fronted blob, or a
    replicated store. What it must not be is lossy: returning a subset of a
    saved snapshot presents as a vault that forgot some people.
    """

    def load(self) -> VaultSnapshot | None:
        """The stored snapshot, or None when nothing has been stored yet.

        None means first run. It does not mean "unreadable": a store that
        cannot read what it holds raises ``VaultStoreError`` instead, so a
        wrong key is never mistaken for a new deployment.
        """
        ...

    def save(self, snapshot: VaultSnapshot) -> None:
        """Replace the stored snapshot. Atomic from a reader's point of view."""
        ...

    def purge(self) -> None:
        """Destroy the stored snapshot.

        Called by ``PrivacyVault.clear``. A clear that left the file behind
        would let a restart resurrect tokens the host has already invalidated.
        """
        ...


class MemoryVaultStore:
    """A store that holds one snapshot in memory.

    For tests, and for a deployment that wants the seam without a file: a
    gateway holding vaults for several sessions can put one of these behind
    each and keep its own persistence above them.
    """

    def __init__(self) -> None:
        self._snapshot: VaultSnapshot | None = None

    def load(self) -> VaultSnapshot | None:
        return self._snapshot

    def save(self, snapshot: VaultSnapshot) -> None:
        self._snapshot = snapshot

    def purge(self) -> None:
        self._snapshot = None


